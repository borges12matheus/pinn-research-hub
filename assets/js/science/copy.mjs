export const copy = locale => locale === 'en' ? en : pt;
export const label = (key, locale) => labels[key]?.[locale === 'en' ? 1 : 0] ?? key;
export function reason(key, locale) {
  if (Object.hasOwn(labels, key)) return label(key, locale);
  const match = /^(.*)_(unverified|differs|mismatch)$/.exec(key);
  const language = locale === 'en' ? 1 : 0;
  if (!match || !reasonFields[match[1]]) return key;
  const tail = match[2] === 'unverified' ? ['sem confirmação','not confirmed'] : ['diverge','differs'];
  return `${reasonFields[match[1]][language]} · ${tail[language]}`;
}
